"use client";

import { useMemo, useState } from "react";

import {
  Search,
  Package,
  DollarSign,
  ShoppingCart,
  AlertTriangle,
  Plus,
  Download,
  MoreHorizontal,
  SlidersHorizontal,
  TrendingUp,
} from "lucide-react";

import {
  productPerformanceData,
  productSummary,
} from "@/data/products";

type ProductStatus = "All" | "In Stock" | "Low Stock" | "Out of Stock";

const statusFilters: ProductStatus[] = [
  "All",
  "In Stock",
  "Low Stock",
  "Out of Stock",
];

const formatCurrency = (amount: number) =>
  new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
  }).format(amount);

export default function ProductsPage() {
  const [searchQuery, setSearchQuery] = useState("");
  const [selectedStatus, setSelectedStatus] =
    useState<ProductStatus>("All");
  const [selectedCategory, setSelectedCategory] =
    useState("All");

  const categories = [
    "All",
    ...new Set(productPerformanceData.map((product) => product.category)),
  ];

  const filteredProducts = useMemo(() => {
    return productPerformanceData.filter((product) => {
      const matchesSearch =
        product.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
        product.id.toLowerCase().includes(searchQuery.toLowerCase()) ||
        product.category.toLowerCase().includes(searchQuery.toLowerCase());

      const matchesStatus =
        selectedStatus === "All" || product.status === selectedStatus;

      const matchesCategory =
        selectedCategory === "All" ||
        product.category === selectedCategory;

      return matchesSearch && matchesStatus && matchesCategory;
    });
  }, [searchQuery, selectedStatus, selectedCategory]);

  const lowStockCount = productPerformanceData.filter(
    (product) => product.status === "Low Stock"
  ).length;

  const outOfStockCount = productPerformanceData.filter(
    (product) => product.status === "Out of Stock"
  ).length;

  const stats = [
    {
      title: "Total Products",
      value: productSummary.totalProducts.toString(),
      description: "Products in your catalog",
      icon: Package,
      iconStyle: "bg-indigo-50 text-indigo-600 dark:bg-indigo-950 dark:text-indigo-400",
    },
    {
      title: "Total Revenue",
      value: formatCurrency(productSummary.totalRevenue),
      description: "Revenue generated by products",
      icon: DollarSign,
      iconStyle: "bg-emerald-50 text-emerald-600 dark:bg-emerald-950 dark:text-emerald-400",
    },
    {
      title: "Units Sold",
      value: productSummary.totalUnitsSold.toLocaleString(),
      description: "Total units sold",
      icon: ShoppingCart,
      iconStyle: "bg-sky-50 text-sky-600 dark:bg-sky-950 dark:text-sky-400",
    },
    {
      title: "Stock Alerts",
      value: (lowStockCount + outOfStockCount).toString(),
      description: `${lowStockCount} low stock · ${outOfStockCount} out of stock`,
      icon: AlertTriangle,
      iconStyle: "bg-amber-50 text-amber-600 dark:bg-amber-950 dark:text-amber-400",
    },
  ];

  const stockStyles: Record<string, string> = {
    "In Stock":
      "bg-emerald-50 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-400",
    "Low Stock":
      "bg-amber-50 text-amber-700 dark:bg-amber-950 dark:text-amber-400",
    "Out of Stock":
      "bg-rose-50 text-rose-700 dark:bg-rose-950 dark:text-rose-400",
  };

  return (
    <div className="mx-auto max-w-7xl space-y-8">
      {/* Page introduction */}
      <section className="flex flex-col justify-between gap-4 sm:flex-row sm:items-center">
        <div>
          <h2 className="text-2xl font-bold text-foreground">
            Products
          </h2>

          <p className="mt-1 text-sm text-muted">
            Manage your product catalog, inventory, and sales performance.
          </p>
        </div>

        <div className="flex flex-wrap gap-3">
          <button
            type="button"
            className="flex items-center justify-center gap-2 rounded-xl border border-border bg-card px-4 py-2.5 text-sm font-semibold text-foreground transition hover:bg-background"
          >
            <Download size={17} />
            Export
          </button>

          <button
            type="button"
            className="flex items-center justify-center gap-2 rounded-xl bg-primary px-4 py-2.5 text-sm font-semibold text-white shadow-lg shadow-indigo-950/10 transition hover:opacity-90"
          >
            <Plus size={17} />
            Add Product
          </button>
        </div>
      </section>

      {/* Product statistics */}
      <section className="grid grid-cols-1 gap-5 sm:grid-cols-2 xl:grid-cols-4">
        {stats.map((stat) => {
          const Icon = stat.icon;

          return (
            <div
              key={stat.title}
              className="rounded-2xl border border-border bg-card p-5 shadow-sm"
            >
              <div className="flex h-11 w-11 items-center justify-center rounded-xl">
                <span className={`flex h-full w-full items-center justify-center rounded-xl ${stat.iconStyle}`}>
                  <Icon size={21} />
                </span>
              </div>

              <p className="mt-5 text-sm font-medium text-muted">
                {stat.title}
              </p>

              <h3 className="mt-1 text-2xl font-bold text-foreground">
                {stat.value}
              </h3>

              <p className="mt-1 text-xs text-muted">
                {stat.description}
              </p>
            </div>
          );
        })}
      </section>

      {/* Product directory */}
      <section className="overflow-hidden rounded-2xl border border-border bg-card shadow-sm">
        {/* Directory heading */}
        <div className="flex flex-col justify-between gap-4 border-b border-border p-5 xl:flex-row xl:items-center">
          <div>
            <h3 className="text-lg font-bold text-foreground">
              Product Inventory
            </h3>

            <p className="mt-1 text-sm text-muted">
              Track product availability, pricing, and performance.
            </p>
          </div>

          {/* Search */}
          <div className="flex items-center gap-2 rounded-xl border border-border bg-background px-3 py-2.5 xl:w-72">
            <Search size={17} className="shrink-0 text-muted" />

            <input
              type="search"
              value={searchQuery}
              onChange={(event) => setSearchQuery(event.target.value)}
              placeholder="Search products..."
              aria-label="Search products"
              className="w-full bg-transparent text-sm text-foreground outline-none placeholder:text-muted"
            />
          </div>
        </div>

        {/* Category filters */}
        <div className="flex flex-wrap items-center gap-2 border-b border-border px-5 py-4">
          {categories.map((category) => (
            <button
              key={category}
              type="button"
              onClick={() => setSelectedCategory(category)}
              className={`rounded-lg px-3 py-2 text-sm font-medium transition ${
                selectedCategory === category
                  ? "bg-primary text-white"
                  : "text-muted hover:bg-background hover:text-foreground"
              }`}
            >
              {category}
            </button>
          ))}
        </div>

        {/* Stock filters */}
        <div className="flex flex-wrap items-center gap-2 border-b border-border px-5 py-4">
          <SlidersHorizontal size={16} className="mr-1 text-muted" />

          {statusFilters.map((status) => (
            <button
              key={status}
              type="button"
              onClick={() => setSelectedStatus(status)}
              className={`rounded-lg px-3 py-2 text-xs font-semibold transition ${
                selectedStatus === status
                  ? "bg-slate-900 text-white dark:bg-slate-100 dark:text-slate-900"
                  : "text-muted hover:bg-background hover:text-foreground"
              }`}
            >
              {status}
            </button>
          ))}

          <span className="ml-auto text-xs text-muted">
            {filteredProducts.length} of {productPerformanceData.length} products
          </span>
        </div>

        {/* Product table */}
        <div className="overflow-x-auto">
          <table className="w-full min-w-[950px] text-left">
            <thead className="bg-background">
              <tr className="text-xs font-semibold uppercase tracking-wider text-muted">
                <th className="px-5 py-4">Product</th>
                <th className="px-5 py-4">Category</th>
                <th className="px-5 py-4">Price</th>
                <th className="px-5 py-4">Units Sold</th>
                <th className="px-5 py-4">Revenue</th>
                <th className="px-5 py-4">Stock</th>
                <th className="px-5 py-4">Status</th>
                <th className="px-5 py-4">Growth</th>
                <th className="px-5 py-4">Action</th>
              </tr>
            </thead>

            <tbody className="divide-y divide-border">
              {filteredProducts.map((product, index) => (
                <tr
                  key={product.id}
                  className="transition hover:bg-background/70"
                >
                  <td className="px-5 py-4">
                    <div className="flex items-center gap-3">
                      <div className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${
                        index % 3 === 0
                          ? "bg-indigo-100 text-indigo-700 dark:bg-indigo-950 dark:text-indigo-300"
                          : index % 3 === 1
                          ? "bg-sky-100 text-sky-700 dark:bg-sky-950 dark:text-sky-300"
                          : "bg-violet-100 text-violet-700 dark:bg-violet-950 dark:text-violet-300"
                      }`}>
                        <Package size={19} />
                      </div>

                      <div>
                        <p className="text-sm font-semibold text-foreground">
                          {product.name}
                        </p>

                        <p className="mt-0.5 text-xs text-muted">
                          {product.id}
                        </p>
                      </div>
                    </div>
                  </td>

                  <td className="px-5 py-4 text-sm text-muted">
                    {product.category}
                  </td>

                  <td className="px-5 py-4 text-sm font-medium text-foreground">
                    {formatCurrency(product.price)}
                  </td>

                  <td className="px-5 py-4 text-sm text-foreground">
                    {product.unitsSold.toLocaleString()}
                  </td>

                  <td className="px-5 py-4 text-sm font-semibold text-foreground">
                    {formatCurrency(product.revenue)}
                  </td>

                  <td className="px-5 py-4 text-sm font-medium text-foreground">
                    {product.stock}
                  </td>

                  <td className="px-5 py-4">
                    <span className={`inline-flex rounded-full px-2.5 py-1 text-xs font-semibold ${stockStyles[product.status]}`}>
                      {product.status}
                    </span>
                  </td>

                  <td className="px-5 py-4">
                    <div className="flex items-center gap-1 text-sm font-semibold text-emerald-600 dark:text-emerald-400">
                      <TrendingUp size={15} />
                      {product.growth}%
                    </div>
                  </td>

                  <td className="px-5 py-4">
                    <button
                      type="button"
                      aria-label={`More actions for ${product.name}`}
                      className="rounded-lg p-2 text-muted transition hover:bg-background hover:text-foreground"
                    >
                      <MoreHorizontal size={19} />
                    </button>
                  </td>
                </tr>
              ))}

              {filteredProducts.length === 0 && (
                <tr>
                  <td
                    colSpan={9}
                    className="px-5 py-12 text-center text-sm text-muted"
                  >
                    No products found. Try another search or filter.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {/* Table footer */}
        <div className="flex flex-col justify-between gap-3 border-t border-border px-5 py-4 sm:flex-row sm:items-center">
          <p className="text-sm text-muted">
            Showing {filteredProducts.length} of {productPerformanceData.length} products
          </p>

          <p className="text-xs text-muted">
            Inventory demonstration data
          </p>
        </div>
      </section>
    </div>
  );
}
